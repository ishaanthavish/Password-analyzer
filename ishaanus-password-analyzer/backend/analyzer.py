# -*- coding: utf-8 -*-
"""
analyzer.py – Core password analysis logic for Ishaanus.

Uses zxcvbn for realistic crack-time estimation and adds:
  - Theoretical entropy (charset-based upper bound)
  - Observed entropy (Shannon entropy – reflects actual character distribution)
  - Per-category character checks
  - Common/weak password detection
  - Dynamic security recommendations

ENTROPY CLARIFICATION
─────────────────────
Two distinct entropy estimates are computed and returned:

  theoretical_entropy
      log2(charset_size) × length
      Upper bound: assumes every character is drawn uniformly at random from
      the full charset pool.  A password made of only one repeated character
      still scores high here, which is why this estimate can be misleading on
      its own.

  observed_entropy
      H × length  where H = -Σ p(c) log2 p(c)  (Shannon entropy per char)
      Lower bound: penalises low character diversity.  "aaaaaaa" scores 0
      because H = 0 for a single distinct character.  This is the more
      honest estimate and is used as the primary display value.

The two estimates bracket the real entropy:
  observed_entropy ≤ real_entropy ≤ theoretical_entropy

PRIVACY: Passwords are only processed in memory and are never logged or stored.
"""

import math
import re
from zxcvbn import zxcvbn

# ── Common weak passwords ────────────────────────────────────────────────────
# This list is intentionally small; zxcvbn covers hundreds of thousands more.
COMMON_PASSWORDS: frozenset = frozenset({
    "123456", "password", "12345678", "qwerty", "123456789",
    "12345", "1234", "111111", "1234567", "dragon", "123123",
    "baseball", "iloveyou", "trustno1", "sunshine", "master",
    "welcome", "shadow", "ashley", "football", "jesus", "michael",
    "ninja", "mustang", "password1", "password123", "admin",
    "letmein", "monkey", "abc123", "pass", "login", "test",
    "qwerty123", "superman", "batman", "access", "hello", "charlie",
})


# ── Entropy helpers ───────────────────────────────────────────────────────────

def _charset_size(password: str) -> int:
    """Return the number of distinct character-class buckets used."""
    size = 0
    if re.search(r"[a-z]", password):
        size += 26
    if re.search(r"[A-Z]", password):
        size += 26
    if re.search(r"\d", password):
        size += 10
    if re.search(r"[^a-zA-Z0-9]", password):
        size += 32   # common printable symbols (~32 on a standard keyboard)
    return size


def calculate_theoretical_entropy(password: str) -> float:
    """
    Return the theoretical (charset-based) entropy in bits.

    Formula: log2(charset_pool_size) × length

    This is an *upper bound* — it assumes the password was generated by
    sampling uniformly at random from the entire charset pool.  Repeated
    or patterned passwords will appear equally strong here, which is a
    known limitation.  Use observed_entropy for a more realistic estimate.
    """
    if not password:
        return 0.0
    cs = _charset_size(password)
    if cs == 0:
        return 0.0
    return round(math.log2(cs) * len(password), 2)


def calculate_observed_entropy(password: str) -> float:
    """
    Return the observed (Shannon) entropy in bits.

    Formula: H × length  where H = -Σ p(c) log2 p(c)

    This is a *lower bound* — it measures the actual information content
    given the character frequencies in the password.  A string of all
    identical characters scores 0 bits regardless of which character it is.
    This is the primary entropy value shown in the UI.
    """
    if not password:
        return 0.0
    length = len(password)
    freq: dict[str, int] = {}
    for ch in password:
        freq[ch] = freq.get(ch, 0) + 1

    shannon_per_char = 0.0
    for count in freq.values():
        p = count / length
        # p * log2(p) is 0 when p = 0; skip to avoid log(0)
        if p > 0:
            shannon_per_char -= p * math.log2(p)

    return round(shannon_per_char * length, 2)


def check_character_categories(password: str) -> dict:
    """
    Check which character categories are present in the password.

    Returns a dict with boolean flags and per-category character counts.
    """
    return {
        "has_uppercase":    bool(re.search(r"[A-Z]", password)),
        "has_lowercase":    bool(re.search(r"[a-z]", password)),
        "has_digits":       bool(re.search(r"\d",    password)),
        "has_symbols":      bool(re.search(r"[^a-zA-Z0-9]", password)),
        "uppercase_count":  len(re.findall(r"[A-Z]", password)),
        "lowercase_count":  len(re.findall(r"[a-z]", password)),
        "digit_count":      len(re.findall(r"\d",    password)),
        "symbol_count":     len(re.findall(r"[^a-zA-Z0-9]", password)),
    }


def generate_recommendations(
    password: str,
    zxcvbn_result: dict,
    categories: dict,
) -> list:
    """
    Generate actionable, specific security recommendations.

    Combines length heuristics, character-category gaps, zxcvbn feedback,
    and common-pattern detection into a deduplicated list of human-readable
    tip strings.

    Returns a list[str].
    """
    tips: list[str] = []
    score  = zxcvbn_result.get("score", 0)
    length = len(password)
    seen:  set[str] = set()   # deduplication guard

    def add(tip: str) -> None:
        if tip not in seen:
            seen.add(tip)
            tips.append(tip)

    # ── Length tips ──────────────────────────────────────────────────────────
    if length < 8:
        add("Use at least 8 characters — 12 or more is strongly recommended.")
    elif length < 12:
        add("Consider extending to 12+ characters for better protection.")
    elif length < 16:
        add("Great length! 16+ characters makes brute-force practically impossible.")

    # ── Character category tips ──────────────────────────────────────────────
    if not categories["has_uppercase"]:
        add("Add uppercase letters (A-Z) to increase complexity.")
    if not categories["has_lowercase"]:
        add("Include lowercase letters (a-z) for a larger character set.")
    if not categories["has_digits"]:
        add("Mix in numbers (0-9) to significantly expand possible combinations.")
    if not categories["has_symbols"]:
        add("Add special characters (!@#$%^&*) for the highest entropy gain.")

    # ── zxcvbn pattern warnings (deduplicated via seen set) ──────────────────
    feedback    = zxcvbn_result.get("feedback", {})
    warning     = feedback.get("warning", "")
    suggestions = feedback.get("suggestions", [])

    if warning:
        add(f"Warning: {warning}")
    for suggestion in suggestions:
        add(suggestion)

    # ── Common-pattern detection ─────────────────────────────────────────────
    if re.search(r"(.)\1{2,}", password):
        add("Avoid repeating the same character multiple times in a row.")
    if re.search(
        r"(012|123|234|345|456|567|678|789|890|abc|bcd|cde|def)",
        password, re.IGNORECASE,
    ):
        add("Avoid sequential patterns like '123' or 'abc'.")
    if re.search(r"(qwerty|asdf|zxcv)", password, re.IGNORECASE):
        add("Keyboard-walk patterns (qwerty, asdf) are easily cracked.")

    # ── Positive / high-score feedback ───────────────────────────────────────
    if score >= 4 and length >= 12:
        add("Excellent password! Consider storing it in a reputable password manager.")
    elif score >= 3:
        add("Good password. A few more characters or symbols would make it excellent.")

    # ── Password manager suggestion (only for weak passwords) ────────────────
    if score < 3:
        add(
            "Consider a password manager (e.g. Bitwarden, 1Password) to generate "
            "and store strong, unique passwords."
        )

    return tips


def is_common_password(password: str) -> bool:
    """Return True if the password appears in the built-in common-password set."""
    return password.lower() in COMMON_PASSWORDS


# ── Empty-password sentinel ───────────────────────────────────────────────────
_EMPTY_RESPONSE: dict = {
    "score":                0,
    "label":                "No Password",
    # Entropy fields — both zero for an empty input
    "entropy":              0.0,   # primary display value (observed)
    "theoretical_entropy":  0.0,
    "observed_entropy":     0.0,
    "length":               0,
    "categories": {
        "has_uppercase":   False,
        "has_lowercase":   False,
        "has_digits":      False,
        "has_symbols":     False,
        "uppercase_count": 0,
        "lowercase_count": 0,
        "digit_count":     0,
        "symbol_count":    0,
    },
    "crack_times": {
        "online_throttling":    "N/A",
        "online_no_throttling": "N/A",
        "offline_slow_hashing": "N/A",
        "offline_fast_hashing": "N/A",
    },
    "is_common":       False,
    "recommendations": ["Enter a password above to begin analysis."],
    # guesses_log10 is always present so callers never need a guard
    "guesses_log10":   0.0,
}


def analyze_password(password: str) -> dict:
    """
    Analyze a password and return a comprehensive security report.

    Args:
        password: Plaintext password to analyze.  Must be a str.

    Returns:
        dict with the following keys:
          score                int   0 (worst) – 4 (best), zxcvbn scale
          label                str   human-readable score label
          entropy              float observed entropy in bits (primary display)
          theoretical_entropy  float charset-based upper-bound entropy in bits
          observed_entropy     float Shannon entropy in bits (same as entropy)
          length               int   character count
          categories           dict  per-class boolean flags and counts
          crack_times          dict  four zxcvbn crack-time scenario strings
          is_common            bool  True if password is in common-password set
          recommendations      list  actionable tip strings
          guesses_log10        float log10 of zxcvbn guess count

    NOTE: The password is NEVER logged, stored, or sent to any external service.
    """
    if not password:
        # Return a copy so callers cannot mutate the sentinel
        return dict(_EMPTY_RESPONSE)

    # ── Run zxcvbn ───────────────────────────────────────────────────────────
    # zxcvbn is the industry-standard realistic password-strength estimator.
    # It is NOT the same as entropy: it estimates how many guesses an
    # intelligent attacker would need, accounting for dictionary words,
    # common substitutions, keyboard walks, etc.
    result = zxcvbn(password)

    score        = result["score"]   # int 0–4
    score_labels = ["Very Weak", "Weak", "Fair", "Strong", "Very Strong"]

    # ── Entropy calculations ─────────────────────────────────────────────────
    theoretical = calculate_theoretical_entropy(password)
    observed    = calculate_observed_entropy(password)
    # Invariant check: observed must never exceed theoretical (floating-point
    # rounding aside).  Cap to avoid confusing the UI.
    observed    = min(observed, theoretical)

    # ── Crack time strings ───────────────────────────────────────────────────
    # zxcvbn models four attacker scenarios — see frontend tooltips for details.
    ct_display = result.get("crack_times_display", {})
    crack_times = {
        "online_throttling":    ct_display.get("online_throttling_100_per_hour",      "N/A"),
        "online_no_throttling": ct_display.get("online_no_throttling_10_per_second",  "N/A"),
        "offline_slow_hashing": ct_display.get("offline_slow_hashing_1e4_per_second", "N/A"),
        "offline_fast_hashing": ct_display.get("offline_fast_hashing_1e10_per_second","N/A"),
    }

    categories = check_character_categories(password)
    common     = is_common_password(password)
    recs       = generate_recommendations(password, result, categories)

    # If the password is in the common list, cap score at 1 (Weak) regardless
    # of what zxcvbn computed — a known password is never "Fair" or better.
    if common:
        score = min(score, 1)

    return {
        "score":               score,
        "label":               score_labels[score],
        # Primary display value — the more honest of the two entropy estimates
        "entropy":             observed,
        "theoretical_entropy": theoretical,
        "observed_entropy":    observed,
        "length":              len(password),
        "categories":          categories,
        "crack_times":         crack_times,
        "is_common":           common,
        "recommendations":     recs,
        "guesses_log10":       round(result.get("guesses_log10", 0), 2),
    }
